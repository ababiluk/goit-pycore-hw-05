def caching_fibonacci():
    # Створюємо словник, який буде нашою "пам'яттю" (кешем)
    # Він порожній на початку, але буде заповнюватися числами
    cache = {}

    def fibonacci(n):
        # Перевіряємо базові випадки, які ми знаємо точно
        if n <= 0:
            return 0
        if n == 1:
            return 1
        
        # Дивимось у наш записник (кеш). 
        # Якщо ми вже колись рахували число для цього n, то просто беремо готове.
        if n in cache:
            return cache[n]

        # Якщо в записнику порожньо, рахуємо число за формулою:
        # сума двох попередніх чисел
        result = fibonacci(n - 1) + fibonacci(n - 2)
        
        # Записуємо результат у наш словник, щоб не рахувати його знову наступного разу
        cache[n] = result
        
        # Повертаємо пораховане число
        return result

    # Повертаємо внутрішню функцію, щоб ми могли її викликати пізніше
    return fibonacci

# Створюємо "екземпляр" нашої функції з кешем
fib = caching_fibonacci()

# Тестуємо, як воно працює
print(fib(10))  # Має бути 55
print(fib(15))  # Має бути 610